"""Generate packed 5x5 bitmap font glyphs for the overlay fragment shader.

Encoding: bit_index = row * 5 + (4 - col)
  row 0 = top, col 0 = left.

Covers printable ASCII 32 (' ') through 126 ('~'), total 95 glyphs.
Glyph index = ASCII code - 32.

Run:  python gen_glyphs.py
"""


def encode(rows: list[str]) -> int:
    """Pack 5 rows of 5 chars ('#'=on, '.'=off) into a 25-bit uint."""
    assert len(rows) == 5 and all(len(r) == 5 for r in rows), \
        f"Bad glyph: {rows}"
    val = 0
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == '#':
                val |= 1 << (r * 5 + (4 - c))
    return val


def decode(val: int) -> list[str]:
    """Unpack a 25-bit uint into 5 rows of 5 chars."""
    rows = []
    for r in range(5):
        row = ''
        for c in range(5):
            row += '#' if val & (1 << (r * 5 + (4 - c))) else '.'
        rows.append(row)
    return rows


